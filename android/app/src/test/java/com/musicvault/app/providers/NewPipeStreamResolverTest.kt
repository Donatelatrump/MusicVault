package com.musicvault.app.providers

import org.junit.Assert.assertEquals
import org.junit.Test

class NewPipeStreamResolverTest {
    @Test
    fun `tries another source caption when preferred track fails`() {
        val expected = com.musicvault.app.lyrics.Lyrics("Available words", emptyList())
        val actual = NewPipeStreamResolver.fetchYoutubeLyrics(
            "fallback001",
            discover = { listOf(caption("en"), caption("en", autoGenerated = true).copy(url = "https://example.test/auto")) },
            load = { if (it.autoGenerated) expected else throw java.io.IOException("Expired caption URL") }
        )
        assertEquals(expected, actual)
    }

    @Test
    fun `parsed lyrics survive eviction of subtitle metadata without network`() {
        val expected = com.musicvault.app.lyrics.Lyrics("Already downloaded", emptyList())
        NewPipeStreamResolver.fetchYoutubeLyrics("cachedVid01", { listOf(caption("en")) }, { expected })
        // The stream metadata cache is also filled by playback without downloading lyrics.
        val field = NewPipeStreamResolver::class.java.getDeclaredField("captionCache").apply { isAccessible = true }
        (field.get(NewPipeStreamResolver) as MutableMap<*, *>).clear()
        val actual = NewPipeStreamResolver.fetchYoutubeLyrics("cachedVid01",
            { throw AssertionError("Cached lyrics must not depend on another extraction") }, { null })
        assertEquals(expected, actual)
    }

    @Test
    fun `retry discovers fresh caption URLs after a failed download`() {
        var discoveryCount = 0
        val expected = com.musicvault.app.lyrics.Lyrics("Fresh captions", emptyList())
        val discover: (String) -> List<NewPipeStreamResolver.CaptionTrack> = {
            discoveryCount++
            listOf(caption("en").copy(url = "https://example.test/captions/$discoveryCount"))
        }
        val load: (NewPipeStreamResolver.CaptionTrack) -> com.musicvault.app.lyrics.Lyrics? = {
            if (it.url.endsWith("/1")) null else expected
        }
        NewPipeStreamResolver.fetchYoutubeLyrics("retryVid001", discover, load)
        assertEquals(expected, NewPipeStreamResolver.fetchYoutubeLyrics("retryVid001", discover, load))
    }

    @Test
    fun `fetches captions for original video when stream cache is missing`() {
        val expected = com.musicvault.app.lyrics.Lyrics("Lyrics", emptyList())
        val actual = NewPipeStreamResolver.fetchYoutubeLyrics(
            "testVideo01",
            discover = { id ->
                assertEquals("testVideo01", id)
                listOf(caption("en"))
            },
            load = { expected }
        )
        assertEquals(expected, actual)
    }

    @Test
    fun `prefers source captions over Spanish translation`() {
        val english = caption(language = "en", translated = false)
        val spanishTranslation = caption(language = "es", translated = true)

        assertEquals(
            english,
            NewPipeStreamResolver.selectCaptionTrack(listOf(spanishTranslation, english))
        )
    }

    @Test
    fun `prefers manual source captions over automatic source captions`() {
        val automatic = caption(language = "en", autoGenerated = true)
        val manual = caption(language = "en", autoGenerated = false)

        assertEquals(
            manual,
            NewPipeStreamResolver.selectCaptionTrack(listOf(automatic, manual))
        )
    }

    @Test
    fun `does not force English when original captions are Spanish`() {
        val spanish = caption(language = "es", translated = false)
        val englishTranslation = caption(language = "en", translated = true)

        assertEquals(
            spanish,
            NewPipeStreamResolver.selectCaptionTrack(listOf(englishTranslation, spanish))
        )
    }

    private fun caption(
        language: String,
        translated: Boolean = false,
        autoGenerated: Boolean = false
    ) = NewPipeStreamResolver.CaptionTrack(
        url = "https://example.test/captions/$language",
        language = language,
        autoGenerated = autoGenerated,
        translated = translated
    )
}
